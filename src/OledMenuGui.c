// i2c (TWI)
void i2c_init() {
    TWBR = 72; // ustawienie zegara SCL 100kHz przy 16MHz
    TWCR = (1 << TWEN);
}

void i2c_start() {
    TWCR = (1 << TWINT) | (1 << TWSTA) | (1 << TWEN);
    while (!(TWCR & (1 << TWINT)));
}

void i2c_stop() {
    TWCR = (1 << TWINT) | (1 << TWSTO) | (1 << TWEN);
}

void i2c_write(uint8_t data) {
    TWDR = data;
    TWCR = (1 << TWINT) | (1 << TWEN);
    while (!(TWCR & (1 << TWINT)));
}

//oled(128x64)
void send_cmd(uint8_t cmd) {
    i2c_start();
    i2c_write(OLED_ADDR);
    i2c_write(0x00);               //komendy
    i2c_write(cmd);
    i2c_stop();
}

void oled_init() {
    _delay_ms(100);
    send_cmd(0xAE);                     // Display OFF
    send_cmd(0xD5); send_cmd(0x80);
    send_cmd(0xA8); send_cmd(0x3F);     // 64 linie
    send_cmd(0xD3); send_cmd(0x00);
    send_cmd(0x40);
    send_cmd(0x8D); send_cmd(0x14);     // Charge Pump ON
    send_cmd(0xA1);                     // Mirror X
    send_cmd(0xC8);                     // Mirror Y
    send_cmd(0xDA); send_cmd(0x12);     // COM pins
    send_cmd(0x20); send_cmd(0x02);     // Page Mode
    send_cmd(0xAF);                     // Display ON
}

void oled_set_cursor(uint8_t row, uint8_t col) {
    send_cmd(0xB0 | row);
    send_cmd(0x00 | (col & 0x0F));
    send_cmd(0x10 | (col >> 4));
}

void oled_clear() {
    for (uint8_t r = 0; r < 8; r++) {
        oled_set_cursor(r, 0);
        i2c_start();
        i2c_write(OLED_ADDR);
        i2c_write(0x40); // tryb danych
        for (uint16_t i = 0; i < 128; i++) i2c_write(0x00);
        i2c_stop();
    }
}

void draw(const uint8_t* d, uint8_t len) {
    i2c_start();
    i2c_write(OLED_ADDR);
    i2c_write(0x40);
    for (uint8_t i = 0; i < len; i++) i2c_write(d[i]);
    i2c_write(0x00);
    i2c_stop();
}
void oled_draw_bitmap(const uint8_t* bitmap) {

	send_cmd(0x21); send_cmd(0); send_cmd(127); // Col addr
	send_cmd(0x22); send_cmd(0); send_cmd(7);   // Page addr

	i2c_start();
	i2c_write(OLED_ADDR);
	i2c_write(0x40);

	for (uint16_t i = 0; i < 1024; i++) {
		i2c_write(pgm_read_byte(&bitmap[i])); // Odczyt z pamięci Flash (PROGMEM)
	}
	i2c_stop();
}
